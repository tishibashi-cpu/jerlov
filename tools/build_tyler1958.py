#: Depths with an entry in Table XI, the glitter noise in the sun's
#: direction, as the radiance tables label them.
GLITTER_DEPTHS = (4.24, 10.4, 16.6, 29.0)
SUN_CELLS = ((20, 0), (30, 0))
OVERSTRUCK = {(4.24, 160, 160): "the last digit is overstruck: 3,230 or "
              "3,290; read as 3,230, which continues the row"}
SUN_NOTE = ("the sun's direction, where the report says the reading could "
            "be low by a factor of 2 (p. 16; Table XI)")


def check(depth, rows):
    """What the tables must satisfy, printed as they are."""
    values = [[float(x) for x in row] for row in rows]
    assert len(values) == len(TILTS), depth
    assert all(len(row) == len(AZIMUTHS) for row in values), depth
    for i in (0, len(TILTS) - 1):
        # Straight up and straight down have no azimuth.
        assert len(set(values[i])) == 1, (depth, TILTS[i])
    for tilt, row in zip(TILTS, values):
        # Away from the sun's azimuth the radiance never rises.
        assert all(a >= b for a, b in zip(row, row[1:])), (depth, tilt)
    return values


zenith = [check(d, TABLES[d])[0][0] for d in sorted(TABLES)]
assert all(a > b for a, b in zip(zenith, zenith[1:])), "zenith with depth"

HEADER = ["depth_m", "tilt_deg", "azimuth_deg", "value", "status", "note"]
rows = 0
path = DATA_DIR / "tyler1958_radiance.csv"
with path.open("w", newline="", encoding="utf-8") as handle:
    writer = csv.writer(handle)
    writer.writerow(HEADER)
    for depth in sorted(TABLES):
        for tilt, row in zip(TILTS, TABLES[depth]):
            for azimuth, value in zip(AZIMUTHS, row):
                status, note = "ok", ""
                if (depth, tilt, azimuth) in OVERSTRUCK:
                    status, note = "suspect", OVERSTRUCK[depth, tilt, azimuth]
                elif depth in GLITTER_DEPTHS and (tilt, azimuth) in SUN_CELLS:
                    status, note = "suspect", SUN_NOTE
                writer.writerow([depth, tilt, azimuth, value, status, note])
                rows += 1
report("tyler1958_radiance.csv", rows)
