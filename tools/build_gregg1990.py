# Bird, R. E. and Riordan, C. (1984), SERI/TR-215-2436, Table 2-1: the
# Neckel and Labs revised extraterrestrial spectrum, W m-2 um-1, at their
# wavelengths from 350 to 690 nm (0.6676 um left out: not a whole nm).
BIRD = {350: 975.5, 360: 975.9, 370: 1119.9, 380: 1103.8, 390: 1033.8,
        400: 1479.1, 410: 1701.3, 420: 1740.4, 430: 1587.2, 440: 1837.0,
        450: 2005.0, 460: 2043.0, 470: 1987.0, 480: 2027.0, 490: 1896.0,
        500: 1909.0, 510: 1927.0, 520: 1831.0, 530: 1891.0, 540: 1898.0,
        550: 1892.0, 570: 1840.0, 593: 1768.0, 610: 1728.0, 630: 1658.0,
        656: 1524.0, 690: 1420.0}

rows = {w: (h, oz, "0.000", "0.000") for w, h, oz in SHORT}
rows.update({w: (h, oz, aw, ao) for w, h, oz, aw, ao in LONG})

problems = []
if sorted(rows) != list(range(350, 701)) or len(SHORT) + len(LONG) != 351:
    problems.append("not every nm from 350 to 700 exactly once")
for w, values in rows.items():
    if any(float(v) < 0 for v in values) or float(values[0]) <= 0:
        problems.append(f"{w} nm: {values}")
# H0 averaged over 11 nm (fewer at the ends) against Bird and Riordan's
# bands: within 5 percent at every one.
for w, bird in BIRD.items():
    near = [float(rows[x][0]) for x in range(max(350, w - 5), min(700, w + 5) + 1)]
    ratio = sum(near) / len(near) / (bird / 1000.0)
    if not 0.95 <= ratio <= 1.05:
        problems.append(f"{w} nm: H0 near it is {ratio:.3f} of Bird and Riordan's")
# The paper's own descriptions: water vapour peaks at 590 nm ("the
# water-vapor absorption peak (590 nm)", p. 1670, and Table 5 there); the
# oxygen "absorption peak near 690 nm" (p. 1669) is at 687 nm in the table.
aw = {w: float(v[2]) for w, v in rows.items() if w < 650}
ao = {w: float(v[3]) for w, v in rows.items()}
if max(aw, key=aw.get) != 590 or max(ao, key=ao.get) != 687:
    problems.append("the water vapour or oxygen peak has moved")
if problems:
    raise SystemExit("\n".join(problems))
print("check: 351 rows, 350-700 nm every nm; nothing negative; H0 within 5 "
      "percent of Bird and Riordan's Table 2-1 at 27 wavelengths; water "
      "vapour peaks at 590 nm, oxygen at 687 nm")

with open(DATA_DIR / "gregg1990_table1.csv", "w", newline="",
          encoding="utf-8") as f:
    wr = csv.writer(f)
    wr.writerow(["wavelength_nm", "H0_W_m2_nm", "a_ozone_per_cm",
                 "a_water_vapour_per_cm", "a_oxygen_per_cm", "status",
                 "note"])
    for w in sorted(rows):
        note = ("water vapour and oxygen not printed below 560 nm; written "
                "as 0" if w < 560 else "")
        wr.writerow([w, *rows[w], "transcribed", note])
report("gregg1990_table1.csv", len(rows))
