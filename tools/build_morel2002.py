def check() -> None:
    for name, rows in TABLES.items():
        assert [c for c, _ in rows] == list(CHL), name
        assert all(len(v) == 7 for _, v in rows), name
    value = {name: {c: [float(x) for x in v] for c, v in rows}
             for name, rows in TABLES.items()}
    # Table 3's f0/Q0 is a fit of its own, close to Table 1 over Table 2.
    worst = max(abs(value["f0_over_Q0"][c][i]
                    / (value["f0"][c][i] / value["Q0"][c][i]) - 1)
                for c in CHL for i in range(7))
    assert worst < 0.02, worst
    # "The overall range of variation of this quantity is 0.08 - 0.12",
    # a rounded range: the table goes down to 0.078632 (660 nm, 10 mg
    # m^-3); and in the blue "between 0.086 and 0.097" (p. 6298).
    allq = [x for c in CHL for x in value["f0_over_Q0"][c]]
    assert min(allq) == 0.078632 and max(allq) < 0.12
    blue = [value["f0_over_Q0"][c][i] for c in CHL for i in (0, 1)]
    assert 0.086 <= min(blue) < 0.087 and 0.097 <= max(blue) < 0.098
    # Q0 "from approximately 3.1 to 4.4" (p. 6298).
    allQ = [x for c in CHL for x in value["Q0"][c]]
    assert 3.1 < min(allQ) < 3.15 and 4.35 < max(allQ) < 4.45
    print(f"Table 3 against Table 1 / Table 2: within {100 * worst:.2f}%")


def main() -> None:
    check()
    out = DATA_DIR / "morel2002_nadir_fq.csv"
    n = 0
    with open(out, "w", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["quantity", "chl_mg_m3", "wavelength_nm", "value"])
        for name, rows in TABLES.items():
            for c, values in rows:
                for w, v in zip(WAVELENGTHS, values):
                    writer.writerow([name, c, w, v])
                    n += 1
    report(out.name, n)


if __name__ == "__main__":
    main()
