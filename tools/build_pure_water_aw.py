# -- checks against the papers; a failure means a transcription error -----

problems = []


def half_unit(text):
    """Half a unit in the last printed digit."""
    return 0.5 * 10.0 ** -len(text.split(".")[1])


# Pope & Fry
pf_wl = [float(w) for w, *_ in POPE1997]
if pf_wl != [380.0 + 2.5 * i for i in range(140)]:
    problems.append("Pope & Fry: not 380-727.5 nm every 2.5 nm")
# p. 8719: "We estimated the percent error by adding the statistical
# standard deviation in quadrature with the error in the absolute value of
# the absorption coefficient for the calibration reference samples
# (estimated at 2%) ... rounding up to an integer percentage."
for w, a, s, pct in POPE1997:
    av, sv, ha, hs = float(a), float(s), half_unit(a), half_unit(s)
    low = 100 * math.hypot((sv - hs) / (av + ha), 0.02)
    high = 100 * math.hypot((sv + hs) / (av - ha), 0.02)
    if not math.ceil(low - 1e-9) <= pct <= math.ceil(high - 1e-9):
        problems.append(f"Pope & Fry {w} nm: percent {pct} does not follow "
                        "from sigma and 2%")
pf_min = min(POPE1997, key=lambda r: float(r[1]))
# Mason et al. p. 7164: "a minimum absorption of 0.0044 m-1 at 418 nm".
if (pf_min[0], round(float(pf_min[1]), 4)) != ("417.5", 0.0044):
    problems.append(f"Pope & Fry: minimum {pf_min[:2]}, not 0.0044 near 418")

# Smith & Baker
sb = {w: r for w, *r in SMITH1981}
if sorted(sb) != list(range(200, 801, 10)):
    problems.append("Smith & Baker: not 200-800 nm every 10 nm")
# Eq. (6): K = a_w + b_m^sw / 2, within the rounding of all three.
SB_SUSPECT = {710}
for w, (k, a, bsw, _bfw) in sb.items():
    gap = float(k) - float(a) - float(bsw) / 2
    tol = half_unit(k) + half_unit(a) + half_unit(bsw) / 2 + 1e-12
    if (abs(gap) > tol) != (w in SB_SUSPECT):
        problems.append(f"Smith & Baker {w} nm: Eq. (6) "
                        f"{'fails' if abs(gap) > tol else 'holds'}")
for w, k, a, half_b in SMITH1981_TABLE2:
    if (k, a) != tuple(sb[w][:2]) and (float(k), float(a)) != (
            float(sb[w][0]), float(sb[w][1])):
        problems.append(f"Smith & Baker {w} nm: Table II repeats K, a_w "
                        "differently")
    if abs(float(half_b) * 1e-3 - float(sb[w][2]) / 2) > (
            half_unit(half_b) * 1e-3 + half_unit(sb[w][2]) / 2 + 1e-12):
        problems.append(f"Smith & Baker {w} nm: Table II b/2 disagrees")

# Mason et al.
ma_wl = [w for w, *_ in MASON2016]
if ma_wl != list(range(250, 300, 10)) + list(range(300, 551, 2)):
    problems.append("Mason: not 250-300 nm every 10 nm, then every 2 nm")
ma_min = min(MASON2016, key=lambda r: float(r[1]))
# Abstract, p. 7163: "A minimum in the absorption coefficient has been
# observed in the UV at 344 nm; the value is 0.000811 +/- 0.000227 m-1."
if ma_min != (344, "0.81", "0.23"):
    problems.append(f"Mason: minimum {ma_min}, not 0.81(23)e-3 at 344 nm")

# Lee et al.
lee = {w: r for w, *r in LEE2015}
if sorted(lee) != list(range(350, 551, 5)):
    problems.append("Lee: not 350-550 nm every 5 nm")
smoothed = sorted(w for w, (_, s, _) in lee.items() if s is not None)
if smoothed != [360, 370, 385, 395, 400]:
    problems.append(f"Lee: smoothed values at {smoothed}")
# p. 555: "We smoothed these dips by a simple average between the
# shoulders". Each dip runs between two unsmoothed neighbours.
for left, right, dip in ((355, 365, (360,)), (365, 375, (370,)),
                         (380, 390, (385,)), (390, 405, (395, 400))):
    mean = (float(lee[left][0]) + float(lee[right][0])) / 2
    for w in dip:
        if abs(float(lee[w][1]) - mean) > 0.00005 + 1e-12:
            problems.append(f"Lee {w} nm: smoothed {lee[w][1]} is not the "
                            f"mean of {left} and {right} nm, {mean:.5f}")

if problems:
    raise SystemExit("\n".join(problems))
print("check: Pope & Fry's 140 percent errors follow from sigma and 2%, "
      "minimum 0.0044 at 417.5 nm; Smith & Baker's Eq. (6) holds within "
      "rounding except at 710 nm, Table II agrees; Mason's minimum is "
      "0.81(23)e-3 at 344 nm; Lee's five smoothed values are the means of "
      "their shoulders")


